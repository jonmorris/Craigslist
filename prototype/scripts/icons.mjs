// Pulls the Material Symbols (Rounded, weight 500) used by the app from the
// official @material-symbols/svg-500 package into src/icons.js, and copies each
// SVG into /brand/icons for Figma. Run: node scripts/icons.mjs
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'

const SRC = 'node_modules/@material-symbols/svg-500/rounded'
const OUT = '../brand/icons'

// app name → Material Symbol name
export const MAP = {
  search: 'search', bell: 'notifications', chevron: 'keyboard_arrow_down', arrow: 'arrow_forward',
  home: 'home', bookmark: 'bookmark', plus: 'add', chat: 'chat_bubble', person: 'person',
  tag: 'sell', house: 'house', briefcase: 'work', wrench: 'handyman', bolt: 'bolt', people: 'group',
  pin: 'location_on', near: 'near_me', snow: 'ac_unit', dresser: 'dresser', shelf: 'shelves', camera: 'photo_camera',
  sparkle: 'brightness_auto', sun: 'light_mode', moon: 'dark_mode', sofa: 'weekend', desk: 'desk',
  back: 'arrow_back', close: 'close', sliders: 'tune', grid: 'grid_view', list: 'view_list', single: 'view_agenda', text: 'view_headline',
  check: 'check', sort: 'swap_vert', history: 'history', fill: 'north_west', trend: 'trending_up',
  share: 'share', heart: 'favorite', 'heart-fill': 'favorite-fill', more: 'more_vert',
  shield: 'verified_user', link: 'link', hide: 'visibility_off', flag: 'flag',
}

mkdirSync(OUT, { recursive: true })
const icons = {}
for (const [name, sym] of Object.entries(MAP)) {
  const svg = readFileSync(`${SRC}/${sym}.svg`, 'utf8')
  icons[name] = [...svg.matchAll(/<path[^>]* d="([^"]+)"/g)].map(m => m[1])
  writeFileSync(`${OUT}/${sym}.svg`, svg.replace('<svg ', '<svg fill="currentColor" '))
}
writeFileSync('src/icons.js', `// GENERATED by scripts/icons.mjs from Material Symbols Rounded (weight 500, Apache-2.0).
// viewBox for every icon: 0 -960 960 960
export const ICONS = ${JSON.stringify(icons)}
`)
const rows = Object.entries(MAP).map(([n, s]) => `| \`${s}\` | ${n} |`).join('\n')
writeFileSync(`${OUT}/README.md`, `# Icons

[Material Symbols](https://fonts.google.com/icons), **Rounded** style, weight **500**, from the official \`@material-symbols/svg-500\` package (Apache 2.0). In Figma, use the Material Symbols plugin with the same settings and search these names. In Compose: \`Icons.Rounded.*\` or the Material Symbols font.

| Material Symbol | used for (prototype name) |
|---|---|
${rows}

Category icons (sell, house, work, handyman, bolt, group) are the candidates for custom brand icons later.
`)
console.log(`wrote ${Object.keys(icons).length} icons to src/icons.js and ${OUT}/`)
