// Generates the Material 3 color scheme (light + dark) from the craigslist
// purple seed with Google's material-color-utilities — the same engine as
// Figma's Material Theme Builder and Android dynamic color — so these tokens
// map 1:1 to a Compose ColorScheme. Run: node scripts/theme.mjs
import { writeFileSync } from 'node:fs'
import {
  argbFromHex, hexFromArgb, Hct, SchemeFidelity, MaterialDynamicColors as C, Blend, TonalPalette,
} from '@material/material-color-utilities'

export const SEED = '#9945C8' // purple sampled from the current app's buttons and peace sign

// Extended colors: section tints + price signals. Harmonized toward the seed and
// built as M3 tonal palettes with capped chroma so containers stay calm.
// [name, source hex, harmonize, max chroma]
export const CUSTOM = [
  ['sale', '#9945C8', false, 36],
  ['housing', '#1E8C7E', true, 26],
  ['jobs', '#C28A12', true, 30],
  ['services', '#3A6FD0', true, 30],
  ['gigs', '#D2553C', true, 30],
  ['community', '#4E8F2F', true, 26],
  ['good', '#2E8B4E', false, 40], // free, below typical
  ['warn', '#C0632A', false, 40], // above typical
]
// M3 custom-color tone mapping: [color, onColor, container, onContainer]
const TONES = { light: [40, 100, 90, 30], dark: [80, 20, 30, 90] }

const ROLES = [
  'primary', 'onPrimary', 'primaryContainer', 'onPrimaryContainer',
  'secondary', 'onSecondary', 'secondaryContainer', 'onSecondaryContainer',
  'tertiary', 'onTertiary', 'tertiaryContainer', 'onTertiaryContainer',
  'error', 'onError', 'errorContainer', 'onErrorContainer',
  'surface', 'onSurface', 'onSurfaceVariant', 'surfaceDim', 'surfaceBright',
  'surfaceContainerLowest', 'surfaceContainerLow', 'surfaceContainer', 'surfaceContainerHigh', 'surfaceContainerHighest',
  'outline', 'outlineVariant', 'inverseSurface', 'inverseOnSurface', 'inversePrimary', 'scrim', 'shadow',
]
const kebab = s => s.replace(/[A-Z]/g, m => '-' + m.toLowerCase())

function block(isDark) {
  const scheme = new SchemeFidelity(Hct.fromInt(argbFromHex(SEED)), isDark, 0)
  const lines = ROLES.map(r => `  --md-sys-color-${kebab(r)}: ${hexFromArgb(C[r].getArgb(scheme))};`)
  for (const [name, hex, harmonize, maxChroma] of CUSTOM) {
    const src = harmonize ? Blend.harmonize(argbFromHex(hex), argbFromHex(SEED)) : argbFromHex(hex)
    const hct = Hct.fromInt(src)
    const pal = TonalPalette.fromHueAndChroma(hct.hue, Math.min(hct.chroma, maxChroma))
    const [c, on, cont, onCont] = TONES[isDark ? 'dark' : 'light'].map(t => hexFromArgb(pal.tone(t)))
    lines.push(`  --md-ext-${name}: ${c};`, `  --md-ext-on-${name}: ${on};`,
      `  --md-ext-${name}-container: ${cont};`, `  --md-ext-on-${name}-container: ${onCont};`)
  }
  return lines.join('\n')
}

const light = block(false)
const dark = block(true)
const css = `/* GENERATED by scripts/theme.mjs — do not edit by hand.
   Material 3 scheme: seed ${SEED}, SchemeFidelity (keeps the brand purple's chroma). */
:root {
${light}
}
@media (prefers-color-scheme: dark) {
  :root:not([data-theme="light"]) {
${dark.replace(/^/gm, '  ')}
    color-scheme: dark;
  }
}
:root[data-theme="dark"] {
${dark}
  color-scheme: dark;
}
`
writeFileSync('src/theme.css', css)
console.log('wrote src/theme.css')
